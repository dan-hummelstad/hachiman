// Phase 1 step 5 — MediaControl sidechannel skeleton, media side.
//
// On boot, when --control-addr is set, hachiman-media:
//
//  1. Dials the control plane over gRPC (insecure creds in phase 1; mTLS lands
//     with the dev-cert provisioning in phase 5).
//  2. Opens the bidirectional Sidechannel stream.
//  3. Sends a RegisterNode envelope first — the control side rejects the
//     stream if anything else arrives first.
//  4. Spawns a heartbeat goroutine that emits a Heartbeat envelope every
//     sidechannelHeartbeatCadence.
//  5. Reads inbound envelopes in a loop. Phase 1 logs and ignores them; later
//     passes dispatch OpenRoom / OpenSession / KickSession / etc.
//  6. On ctx cancel or stream error, the stream is closed cleanly.
//
// If --control-addr is empty (embedded / standalone mode) the entire
// sidechannel client is skipped — the binary runs as a self-contained SFU.

const (
	// sidechannelHeartbeatCadence matches the mediaHeartbeatCadence on the
	// control side. Lowering this on one side without the other shortens the
	// eviction window asymmetrically; keep in lockstep.
	sidechannelHeartbeatCadence = 10 * time.Second

	// sidechannelReconnectBackoffMin / Max bracket the exponential backoff
	// between reconnect attempts. We start at 1s, double each failure (capped
	// at 30s), and add ±25% jitter so a control flap doesn't synchronise the
	// whole fleet into a thundering herd. A successful stream resets back to
	// the minimum.
	sidechannelReconnectBackoffMin = 1 * time.Second
	sidechannelReconnectBackoffMax = 30 * time.Second
)

// sidechannelClient runs the media-side sidechannel until ctx is cancelled.
// It opens one persistent stream at a time and reconnects on failure. The
// caller blocks on this function (run via a goroutine in main).
type sidechannelClient struct {
	controlAddr string
	region      string
	nodeID      string
	version     string

	// maxSessions is the per-node session capacity declaration sent in
	// RegisterNode. Phase 1 derives a sane default from CPU cores; later
	// passes wire it to the SFU's actual capacity model.
	maxSessions uint32

	logger *log.Logger

	// runtime owns the SFU + session/room state. Inbound envelopes from
	// control are dispatched to runtime.HandleEnvelope; outbound envelopes
	// generated by the runtime (SDP offers, ICE candidates, session
	// lifecycle notifications) flow back out via the sender wired in
	// runOnce. Non-nil after newSidechannelClient.
	runtime *sfuRuntime
}

func newSidechannelClient(a args, logger *log.Logger) *sidechannelClient {
	return &sidechannelClient{
		controlAddr: a.ControlAddr,
		region:      a.Region,
		// Fresh UUID per boot. On reconnect after a partition we keep the
		// SAME UUID across reconnect attempts for the lifetime of this
		// process, so control can rejoin existing rooms to this node when
		// the partition heals (per the MediaControl.proto comment on
		// RegisterNode.node_id).
		nodeID:      uuid.NewString(),
		version:     mediaBuildVersion(),
		maxSessions: defaultMaxSessions(),
		logger:      logger,
		runtime:     newSFURuntime(logger, a.Region),
	}
}

// run drives the connect → register → heartbeat → recv loop until ctx is
// cancelled. Each iteration of the outer for-loop is one connection attempt;
// failures backoff exponentially (capped, jittered) and retry. A successful
// stream connect resets the backoff to the minimum.
func (c *sidechannelClient) run(ctx context.Context) {
	if c.controlAddr == "" {
		// Embedded mode: nothing to do.
		return
	}

	// rng is goroutine-local — the run loop is single-threaded so no lock is
	// needed. Seed from time.Now so two media nodes starting at the same
	// nanosecond don't synchronise their jitter.
	rng := rand.New(rand.NewSource(time.Now().UnixNano() ^ int64(uuid.New().ID())))
	backoff := sidechannelReconnectBackoffMin

	for {
		if ctx.Err() != nil {
			return
		}
		start := time.Now()
		err := c.runOnce(ctx)
		if err != nil {
			c.logger.Printf("[sidechannel] stream ended: %v", err)
		}
		// If the stream stayed up for at least one heartbeat cadence we treat
		// it as a successful connect and reset the backoff. Otherwise grow it
		// exponentially up to the cap.
		if time.Since(start) >= sidechannelHeartbeatCadence {
			backoff = sidechannelReconnectBackoffMin
		} else {
			backoff = nextBackoff(backoff, rng)
		}
		// Backoff before the next reconnect attempt, but exit promptly if the
		// process is shutting down.
		select {
		case <-ctx.Done():
			return
		case <-time.After(backoff):
		}
	}
}

// nextBackoff returns the next backoff duration, capped at the configured max
// and shaken by ±25% jitter. Pure helper so it's trivially testable.
func nextBackoff(cur time.Duration, rng *rand.Rand) time.Duration {
	next := cur * 2
	if next > sidechannelReconnectBackoffMax {
		next = sidechannelReconnectBackoffMax
	}
	// jitter is in the range [-0.25, +0.25].
	jitter := (rng.Float64() - 0.5) * 0.5
	d := time.Duration(float64(next) * (1.0 + jitter))
	if d < sidechannelReconnectBackoffMin {
		d = sidechannelReconnectBackoffMin
	}
	return d
}

// runOnce dials control, opens the stream, sends RegisterNode, and runs the
// heartbeat + receive loops until something fails or ctx is cancelled. The
// returned error reports why the connection ended; nil means a clean shutdown.
func (c *sidechannelClient) runOnce(ctx context.Context) error {
	conn, err := grpc.NewClient(c.controlAddr,
		grpc.WithTransportCredentials(insecure.NewCredentials()),
	)
	if err != nil {
		return fmt.Errorf("dial %q: %w", c.controlAddr, err)
	}
	defer conn.Close()

	client := mediaproto.NewMediaControlClient(conn)

	streamCtx, cancel := context.WithCancel(ctx)
	defer cancel()

	stream, err := client.Sidechannel(streamCtx)
	if err != nil {
		return fmt.Errorf("open sidechannel stream: %w", err)
	}

	// gRPC streams are not safe for concurrent Send — the runtime's outbound
	// envelopes (SDP offers, ICE candidates) AND the heartbeat goroutine
	// both call Send. Wrap with a per-stream mutex so the framing stays
	// intact.
	var sendMu sync.Mutex
	send := func(env *mediaproto.Envelope) error {
		sendMu.Lock()
		defer sendMu.Unlock()
		return stream.Send(env)
	}

	// First envelope MUST be RegisterNode — control rejects anything else.
	if err := send(c.registerEnvelope()); err != nil {
		return fmt.Errorf("send RegisterNode: %w", err)
	}
	c.logger.Printf("[sidechannel] registered node=%s region=%s control=%s",
		c.nodeID, c.region, c.controlAddr)

	// Wire the runtime's outbound channel to this stream's send. Cleared
	// on return so a brief reconnect gap doesn't leak the previous stream
	// reference.
	c.runtime.SetSender(send)
	defer c.runtime.SetSender(nil)

	// Heartbeat goroutine. The heartbeat loop owns the streamCtx cancel so a
	// send failure tears the stream down — otherwise `stream.Recv()` below
	// would block indefinitely (phase 1 control rarely sends) and runOnce
	// would never return into the reconnect backoff. With cancel wired in,
	// a heartbeat-send failure unwinds Recv with codes.Canceled and runOnce
	// returns. See HIGH #1 in the phase-1 follow-up review.
	hbErrCh := make(chan error, 1)
	go c.heartbeatLoop(streamCtx, cancel, send, hbErrCh)

	// Receive loop runs inline so a stream-recv error tears the connection
	// down without needing a third goroutine.
	for {
		select {
		case err := <-hbErrCh:
			if err != nil {
				return fmt.Errorf("heartbeat: %w", err)
			}
			return nil
		default:
		}

		env, err := stream.Recv()
		if err != nil {
			// Drain hbErrCh non-blocking so a heartbeat failure surfaces as
			// the canonical error (recv will report codes.Canceled when the
			// heartbeat goroutine cancelled streamCtx; the underlying cause
			// is the heartbeat send).
			select {
			case hbErr := <-hbErrCh:
				if hbErr != nil {
					return fmt.Errorf("heartbeat: %w", hbErr)
				}
			default:
			}
			if errors.Is(err, io.EOF) {
				return nil
			}
			return fmt.Errorf("recv: %w", err)
		}
		c.dispatch(env)
	}
}

// heartbeatLoop emits Heartbeat envelopes on the cadence until ctx is
// cancelled or the stream send fails. Reports terminal errors on errCh.
//
// cancel cancels the stream context owned by runOnce. The heartbeat loop calls
// it on send failure so a stuck stream.Recv() in runOnce unwinds with
// codes.Canceled instead of blocking forever. Without this, a half-broken
// stream (send-side dead, recv-side idle) would leave the node alive in the
// control registry until the sweeper evicts at 3x cadence AND prevent the
// media-side reconnect loop from ever firing.
//
// Phase 1 final pass: ActiveSessions / ActiveRooms come from the SFU runtime's
// session/room maps. CPU% / memory% are still zero — those need gopsutil and
// aren't worth the dep for this pass (follow-up #9 partial).
func (c *sidechannelClient) heartbeatLoop(ctx context.Context, cancel context.CancelFunc,
	send envelopeSender, errCh chan<- error) {
	ticker := time.NewTicker(sidechannelHeartbeatCadence)
	defer ticker.Stop()
	// Belt-and-suspenders: if the loop exits for any reason, tear down the
	// stream context so the recv loop unwinds. The send-failure branch below
	// also calls cancel explicitly so the recv loop is unblocked before the
	// error lands on errCh.
	defer cancel()

	for {
		select {
		case <-ctx.Done():
			errCh <- nil
			return
		case <-ticker.C:
			active, rooms := c.runtime.stats()
			env := &mediaproto.Envelope{
				IdempotencyKey: uuid.NewString(),
				Payload: &mediaproto.Envelope_Heartbeat{
					Heartbeat: &mediaproto.Heartbeat{
						ActiveSessions: active,
						ActiveRooms:    rooms,
						// TODO: CPU% / mem% — needs gopsutil; not worth the
						// dep for phase 1. Placement will tolerate zeros
						// until phase 3 wires the real metric.
						CpuFraction:    0,
						MemoryFraction: 0,
						Accepting:      true,
					},
				},
			}
			if err := send(env); err != nil {
				// Cancel the stream context BEFORE pushing the error onto
				// errCh — the recv loop is blocked in stream.Recv() and
				// won't observe errCh until Recv returns. Cancelling first
				// unwinds Recv with codes.Canceled; runOnce returns into
				// reconnect backoff.
				cancel()
				errCh <- err
				return
			}
		}
	}
}

// registerEnvelope builds the first envelope sent on every new connection.
func (c *sidechannelClient) registerEnvelope() *mediaproto.Envelope {
	return &mediaproto.Envelope{
		IdempotencyKey: uuid.NewString(),
		Payload: &mediaproto.Envelope_RegisterNode{
			RegisterNode: &mediaproto.RegisterNode{
				NodeId:          c.nodeID,
				Region:          c.region,
				SidechannelAddr: "", // media doesn't expose an inbound sidechannel; control reverse-dial is a phase 3+ concern.
				MaxSessions:     c.maxSessions,
				Version:         c.version,
			},
		},
	}
}

// dispatch is the inbound-envelope handler. Phase 1 final pass: housekeeping
// (Ack, StreamError) stays inline; everything else is delegated to the SFU
// runtime which owns the session/room state machine.
func (c *sidechannelClient) dispatch(env *mediaproto.Envelope) {
	if env == nil {
		return
	}
	switch payload := env.GetPayload().(type) {
	case *mediaproto.Envelope_Ack:
		_ = payload
	case *mediaproto.Envelope_Error:
		if c.logger != nil && payload.Error != nil {
			c.logger.Printf("[sidechannel] stream error from control: code=%v message=%q for_key=%q",
				payload.Error.GetCode(), payload.Error.GetMessage(), payload.Error.GetForKey())
		}
	default:
		c.runtime.HandleEnvelope(env)
	}
}

// defaultMaxSessions is a conservative per-CPU estimate so a freshly-booted
// node declares a non-zero capacity before real metrics wire in. The 50× factor
// is a placeholder; real placement work overrides this from configuration.
func defaultMaxSessions() uint32 {
	cores := runtime.NumCPU()
	if cores <= 0 {
		cores = 1
	}
	return uint32(cores) * 50
}

// mediaBuildVersion returns a coarse build identifier for the RegisterNode
// payload. Phase 1 hardcodes "dev"; the build script writes the real version
// via ldflags later (matches the hachiman-control `version` global pattern).
func mediaBuildVersion() string {
	return "dev"
}
