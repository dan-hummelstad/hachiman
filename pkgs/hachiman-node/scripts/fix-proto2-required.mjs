#!/usr/bin/env node
/**
 * Post-processes the protobuf-ts–generated .ts files to fix a proto2
 * footgun: the generator emits `if (message.<field> !== <default>)` guards
 * around the wire-write of `required` scalar fields. That's correct for
 * proto3 (implicit-presence) but wrong for proto2 — `required` fields MUST
 * always be on the wire, regardless of value.
 *
 * Concrete impact before this fix: querying the root channel's ACL sends
 * `ACL { channelId: 0, query: true }`. The encoder skips `channel_id` (it
 * equals the proto3 default), the Go server's `proto.Unmarshal` fails the
 * required-field check, and Grumble calls `client.Panic(err)` which tears
 * down the TLS socket. The client just sees its next Ping fail with
 * "socket not writable" and the fetchAcl command times out.
 *
 * Upstream issue: https://github.com/timostamm/protobuf-ts/issues/146
 *
 * We strip the conditional and emit the writer call unconditionally for
 * any block preceded by `/* required <type> <name> = <n>; *\/`. The
 * comment is generated by protobuf-ts itself so the marker is reliable.
 *
 * Run via `pnpm -F @hachiman/hachiman-node generate-proto`, which chains
 * this script after protoc.
 */
import { readdirSync, readFileSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';
import { fileURLToPath } from 'node:url';

const here = fileURLToPath(new URL('.', import.meta.url));
const protoDir = join(here, '..', 'src', 'mumbleproto');

// Match a `required` field block in `internalBinaryWrite`:
//
//   /* required <whatever> = <num>; */
//   if (message.<name> !== <default>)
//       writer.tag(<num>, WireType.X).Y(message.<name>);
//
// Capture the leading comment line and the writer line; drop the if guard.
// Indentation: we keep the comment at its own indent and re-indent the
// writer to match (one level less than its original — i.e. where the `if`
// used to be).
const PATTERN =
  /([ \t]*)(\/\* required [^*]*?\*\/)\n[ \t]*if \(message\.\w+ !== [^)]+\)\n[ \t]+(writer\.[^\n]+)/g;

function patchFile(path) {
  const before = readFileSync(path, 'utf8');
  let count = 0;
  const after = before.replace(
    PATTERN,
    (_match, indent, comment, writerCall) => {
      count++;
      return `${indent}${comment}\n${indent}${writerCall}`;
    },
  );
  if (count > 0) {
    writeFileSync(path, after);
    console.log(
      `[fix-proto2-required] patched ${count} required-field block(s) in ${path}`,
    );
  }
}

function main() {
  const files = readdirSync(protoDir).filter(f => f.endsWith('.ts'));
  for (const f of files) patchFile(join(protoDir, f));
}

main();
